// Writes the live sky's assets: the still sky's glyphs and colour maps
// and two cloud layers (near and far; red: shade, green: cloud) into
// assets/, and the numbers the renderer needs as src/art.ts. With "-" for
// convDir, the still sky stays as it is and only the clouds are written.
//   node scripts/write.mjs <convDir|-> <cloudDir>
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
const ROOT = new URL("..", import.meta.url).pathname.replace(/\/$/, "");
const require = createRequire(import.meta.url);
const sharp = require("sharp");
const [dir, cloudDir] = process.argv.slice(2);
const OUT = `${ROOT}/assets`;
mkdirSync(OUT, { recursive: true });
const keepStill = dir === "-";
const meta = keepStill
  ? (await import(`${ROOT}/src/art.ts`)).sky
  : JSON.parse(readFileSync(path.join(dir, "sky.json"), "utf8"));
if (!keepStill) {
  writeFileSync(`${OUT}/sky.txt`, readFileSync(path.join(dir, "sky.txt"), "utf8"));
  for (const mode of ["light", "dark"])
    await sharp(path.join(dir, `sky-${mode}.png`)).webp({ quality: 90, smartSubsample: true }).toFile(`${OUT}/sky-${mode}.webp`);
}
for (const layer of ["near", "far"])
  await sharp(path.join(cloudDir, `clouds-${layer}.png`)).removeAlpha().webp({ lossless: true, effort: 6 }).toFile(`${OUT}/clouds-${layer}.webp`);
try {
  unlinkSync(`${OUT}/clouds.webp`);
} catch {}
const cm = await sharp(path.join(cloudDir, "clouds-near.png")).metadata();
const files = ["sky.txt", "sky-light.webp", "sky-dark.webp", "clouds-near.webp", "clouds-far.webp"];
const hash = createHash("sha256");
for (const f of files) hash.update(readFileSync(`${OUT}/${f}`));
const version = hash.digest("hex").slice(0, 10);
const ts = `// Generated by scripts/write.mjs: the numbers behind the live sky. The
// still sky (a painted sky with its clouds taken out) is glyphs in
// assets/sky.txt, a glyph per cell, coloured by
// assets/sky-{light,dark}.webp, a pixel per cell. Its clouds drift over it
// in two layers, assets/clouds-{near,far}.webp at half the page's pixels: clouds
// cut from the painting, red for how shaded and green for how much
// cloud. They tile every \`period\` page pixels, so they can drift and
// loop.

export const sky = {
  columns: ${meta.columns},
  rows: ${meta.rows},
  cellWidth: ${meta.cellWidth},
  cellHeight: ${meta.cellHeight},
  /** Page pixels after which the clouds repeat. */
  period: ${cm.width * 2},
  /** A cloud layer's own size, in its pixels (half the page's). */
  cloudWidth: ${cm.width},
  cloudHeight: ${cm.height},
  version: "${version}",
};
`;
writeFileSync(`${ROOT}/src/art.ts`, ts);
console.log("written, version", version, files.map((f) => `${f} ${readFileSync(`${OUT}/${f}`).length}`).join(", "));
